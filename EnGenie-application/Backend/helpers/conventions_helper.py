from __future__ import annotations


_LAYER_TO_VALVE_LAYER = {1: None, 2: None, 3: 'hand', 4: 'relief'}


_LAYER_LABELS = {1: 'process', 2: 'control', 3: 'mechanical', 4: 'safety'}


_SUGGESTED_TYPE_TO_EQUIP_TYPE = {
    'heat_exchanger': 'Heat Exchanger',
    'vessel': 'Vessel / Drum',
    'pump': 'Pump',
    'compressor': 'Compressor',
    'reactor': 'Reactor',
    'tank': 'Tank',
    'filter': 'Filter',
    'separator': 'Separator',
    'column': 'Column / Tower',
    'cooler': 'Cooler',
}


_SUGGESTED_TYPE_TO_VALVE_LAYER = {
    'control_valve': 'control',
    'hand_valve':    'hand',
    'check_valve':   'check',
    'relief_valve':  'relief',
    'isolation_valve': 'isolation',
    # aliases
    'control': 'control', 'hand': 'hand', 'check': 'check',
    'relief': 'relief',   'isolation': 'isolation',
}


def _build_conventions_md(company: str, prefixes: list,
                           drawing_format: str, tag_numbering: dict) -> str:
    """Generate a conventions.md from discover-conventions results."""
    lines = [
        f'# {company} — P&ID Conventions',
        f'> Auto-generated by convention discovery. Review and correct as needed.',
        '',
    ]

    # §1 Equipment
    equip_rows = [p for p in prefixes if p.get('suggested_layer') == 1
                  and 'valve' not in (p.get('suggested_type') or '').lower()]
    valve_rows = [p for p in prefixes if p.get('suggested_layer') in (1, 3, 4)
                  and 'valve' in (p.get('suggested_type') or '').lower()]
    instr_rows = [p for p in prefixes if p.get('suggested_layer') == 2]

    lines += ['## 1. Equipment Tag Prefixes',
              '| Equipment Type | Standard ISA | This Company | Notes |',
              '|---|---|---|---|']
    for row in equip_rows:
        etype = _SUGGESTED_TYPE_TO_EQUIP_TYPE.get(
            (row.get('suggested_type') or '').lower(), 'Other')
        lines.append(f'| {etype} | — | {row["prefix"]}- | {row.get("context","")} |')

    if equip_rows:
        lines += ['', '### Equipment Kind Mapping (for PlantSketch palette)',
                  '| Company Prefix | Editor Kind | Symbol |',
                  '|---|---|---|']
        _type_to_kind = {
            'heat_exchanger': 'hx_st', 'vessel': 'vessel_v', 'pump': 'pump_cent',
            'compressor': 'comp_cent', 'reactor': 'cstr', 'tank': 'tank_atm',
            'filter': 'filter_pf', 'separator': 'vessel_v', 'column': 'column',
            'cooler': 'condenser',
        }
        for row in equip_rows:
            kind = _type_to_kind.get((row.get('suggested_type') or '').lower(), 'vessel_v')
            lines.append(f'| {row["prefix"]}- | {kind} | {row.get("suggested_type","")} |')

    lines += ['', '## 2. Valve Classification',
              '> DEFAULT RULE: Valves with NO signal connection → isolation (hidden).',
              '> Valves WITH signal connections → control (shown).',
              '',
              '| Prefix | Full Name | Layer | Notes |',
              '|---|---|---|---|']
    for row in valve_rows:
        vl = _SUGGESTED_TYPE_TO_VALVE_LAYER.get(
            (row.get('suggested_type') or '').lower(), 'control')
        lines.append(f'| {row["prefix"]}- | {row.get("context","—")} | {vl} | |')

    lines += ['', '## 3. Instrument Tag Prefixes',
              '> Standard ISA first-letter codes apply unless overridden.',
              '',
              '| Prefix | Standard ISA Meaning | This Company | Notes |',
              '|---|---|---|---|']
    for row in instr_rows:
        lines.append(f'| {row["prefix"]} | {row.get("suggested_type","")} | Same | |')

    if tag_numbering:
        fd = tag_numbering.get('first_digit', '')
        ex = tag_numbering.get('example', '')
        lines += ['', '## 4. Tag Numbering Convention',
                  f'- First digit meaning: {fd}',
                  f'- Example: {ex}']

    if drawing_format:
        lines += ['', '## 5. Drawing Numbering',
                  f'- Format: {drawing_format}']

    lines += ['', '## 7. Process Flow',
              '- Main flow direction: left-to-right',
              '',
              '## 10. Default Assumptions',
              '- Unrecognized valve with no signal → isolation (hidden)',
              '- Unrecognized valve with signal → control (shown)',
              '- Unrecognized instrument → transmitter',
              '- Unrecognized equipment → vessel',
              '']
    return '\n'.join(lines)
